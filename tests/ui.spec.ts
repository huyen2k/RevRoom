 await expect(page.locator('.room-grid .room')).toHaveCount(300);
 await page.getByRole('button',{name:'Monte Carlo',exact:true}).click();
 await page.locator('.batch-hero button').click();
 await expect(page.locator('.batch-hero table').first()).toBeVisible({timeout:30000});
 await page.getByRole('button',{name:'Phương pháp'}).click();
 await expect(page.getByRole('heading',{name:'Bảo vệ tồn kho cho nhóm giá cao'})).toBeVisible();
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
