 await page.getByRole('button',{name:'Chạy đủ 30 ngày'}).click();
 await expect(page.locator('progress')).toHaveAttribute('value','30');
 expect(await page.locator('.recharts-surface').count()).toBe(3);
 await expect(page.getByRole('heading',{name:'Bảng giá thay đổi theo từng ngày'})).toBeVisible();
 await expect(page.locator('.log').filter({hasText:'Bảng giá thay đổi theo từng ngày'}).locator('tbody tr')).toHaveCount(30);
 const download=page.waitForEvent('download');await page.getByRole('button',{name:'CSV'}).click();expect((await download).suggestedFilename()).toContain('seed-42');
 await page.getByRole('button',{name:'Animation khách'}).click();
 await expect(page.getByText('WTP:',{exact:false}).first()).toBeVisible();
